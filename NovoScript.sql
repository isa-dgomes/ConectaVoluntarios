CREATE TABLE endereco (
    id_endereco BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidade VARCHAR(100) NOT NULL,
    estado VARCHAR(50) NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(20) NOT NULL,
    cep VARCHAR(8),
    bairro VARCHAR(100)
);


CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_endereco BIGINT NOT NULL UNIQUE,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    telefone VARCHAR(20) NOT NULL,
    aceitou_termos BOOLEAN NOT NULL DEFAULT FALSE,
    data_aceite_termos TIMESTAMPTZ,

    CONSTRAINT fk_usuario_endereco
        FOREIGN KEY (id_endereco)
        REFERENCES endereco(id_endereco)
        ON DELETE RESTRICT,	
	-- restric valida que para excluir um endereco, não deve haver um usuario vinculado


	-- o check serve para validar dados antes de salvar, por seguranca
	CONSTRAINT chk_aceite_termos
        CHECK (
            (aceitou_termos = TRUE AND data_aceite_termos IS NOT NULL)
            OR
            (aceitou_termos = FALSE AND data_aceite_termos IS NULL)
        )
);


CREATE TABLE voluntario (
	-- somente primary key pois herda de usuario, nao deve ser incremental
    id_usuario BIGINT PRIMARY KEY,
    habilidades TEXT,
    experiencia TEXT,

    CONSTRAINT fk_voluntario_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE
);


CREATE TABLE organizacao (
    id_usuario BIGINT PRIMARY KEY,
    razao_social VARCHAR(180),
    cnpj VARCHAR(14) UNIQUE,
    descricao TEXT NOT NULL,
    tipo_organizacao VARCHAR(100),
    responsavel VARCHAR(120) NOT NULL,
    logo TEXT,

	--cacade para de
    CONSTRAINT fk_organizacao_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES usuario(id_usuario)
        ON DELETE CASCADE,

	--regex para validar formato do cnpj
    CONSTRAINT chk_cnpj
        CHECK (cnpj ~ '^[0-9A-Z]{12}[0-9]{2}$')
);


CREATE TABLE area_atuacao (
    id_area_atuacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_area VARCHAR(100) NOT NULL UNIQUE
);


CREATE TABLE voluntario_area_interesse (
    id_voluntario BIGINT NOT NULL,
    id_area_atuacao BIGINT NOT NULL,

    PRIMARY KEY (id_voluntario, id_area_atuacao),

    CONSTRAINT fk_interesse_voluntario
        FOREIGN KEY (id_voluntario)
        REFERENCES voluntario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_interesse_area
        FOREIGN KEY (id_area_atuacao)
        REFERENCES area_atuacao(id_area_atuacao)
        ON DELETE RESTRICT
);


CREATE TABLE voluntario_disponibilidade (
    id_voluntario BIGINT NOT NULL,
    dia_semana VARCHAR(25) NOT NULL,

    PRIMARY KEY (id_voluntario, dia_semana),

    CONSTRAINT fk_disponibilidade_voluntario
        FOREIGN KEY (id_voluntario)
        REFERENCES voluntario(id_usuario)
        ON DELETE CASCADE,

	-- enums definidos
    CONSTRAINT chk_dia_disponibilidade
        CHECK (dia_semana IN (
            'SEGUNDA',
			'TERCA',
			'QUARTA',
			'QUINTA',
			'SEXTA',
			'SABADO',
			'DOMINGO'
        ))
);


CREATE TABLE voluntario_periodo (
    id_voluntario BIGINT NOT NULL,
    periodo VARCHAR(15) NOT NULL,

    PRIMARY KEY (id_voluntario, periodo),

    CONSTRAINT fk_periodo_voluntario
        FOREIGN KEY (id_voluntario)
        REFERENCES voluntario(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT chk_periodo_voluntario
        CHECK (periodo IN (
            'MANHA',
			'TARDE',
			'NOITE'
        ))
);

CREATE TABLE oportunidade (
    id_oportunidade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organizacao BIGINT NOT NULL,
    id_area_atuacao BIGINT NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL,
    quantidade_vagas INTEGER NOT NULL,
    data_inicio DATE NOT NULL,
    data_fim DATE NOT NULL,
    modalidade VARCHAR(30) NOT NULL,
    local_oportunidade VARCHAR(255) NOT NULL,
    requisitos TEXT,
    bloqueada_por_lotacao BOOLEAN NOT NULL DEFAULT FALSE,
    status_oportunidade VARCHAR(30) NOT NULL DEFAULT 'aberta',
    oferece_certificado BOOLEAN NOT NULL DEFAULT FALSE,
    carga_horaria INTEGER,
    exige_documentos BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_oportunidade_organizacao
        FOREIGN KEY (id_organizacao)
        REFERENCES organizacao(id_usuario)
        ON DELETE RESTRICT,

    CONSTRAINT fk_oportunidade_area
        FOREIGN KEY (id_area_atuacao)
        REFERENCES area_atuacao(id_area_atuacao)
        ON DELETE RESTRICT,

    CONSTRAINT chk_quantidade_vagas
        CHECK (quantidade_vagas > 0),

    CONSTRAINT chk_datas_oportunidade
        CHECK (data_fim >= data_inicio),

    CONSTRAINT chk_status_oportunidade
        CHECK (status_oportunidade IN (
            'ABERTA',
            'EM_ANALISE',
            'EM_ANDAMENTO',
            'CONCLUIDA'
        )),

    CONSTRAINT chk_modalidade
        CHECK (modalidade IN (
            'PRESENCIAL',
            'ONLINE',
            'HIBRIDA'
        )),

    CONSTRAINT chk_carga_horaria
        CHECK (
            (oferece_certificado = TRUE AND carga_horaria > 0)
            OR
            (oferece_certificado = FALSE AND carga_horaria IS NULL)
        )
);



CREATE TABLE horario_oportunidade (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oportunidade BIGINT NOT NULL,
    dia_semana VARCHAR(25) NOT NULL,
    periodo VARCHAR(15) NOT NULL,

    CONSTRAINT fk_horario_oportunidade
        FOREIGN KEY (id_oportunidade)
        REFERENCES oportunidade(id_oportunidade)
        ON DELETE CASCADE,

    CONSTRAINT uq_horario_oportunidade
        UNIQUE (id_oportunidade, dia_semana, periodo),

    CONSTRAINT chk_dia_horario
        CHECK (dia_semana IN (
            'SEGUNDA',
			'TERCA',
			'QUARTA',
			'QUINTA',
			'SEXTA',
			'SABADO',
			'DOMINGO'
        )),

    CONSTRAINT chk_periodo_horario
        CHECK (periodo IN (
            'MANHA',
            'TARDE',
            'NOITE'
        ))
);

CREATE TABLE candidatura (
    id_candidatura BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_voluntario BIGINT NOT NULL,
    id_oportunidade BIGINT NOT NULL,
    data_candidatura TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_candidatura VARCHAR(30) NOT NULL DEFAULT 'PENDENTE',
    mensagem TEXT,

    CONSTRAINT fk_candidatura_voluntario
        FOREIGN KEY (id_voluntario)
        REFERENCES voluntario(id_usuario)
        ON DELETE RESTRICT,

    CONSTRAINT fk_candidatura_oportunidade
        FOREIGN KEY (id_oportunidade)
        REFERENCES oportunidade(id_oportunidade)
        ON DELETE RESTRICT,

    CONSTRAINT uq_candidatura
        UNIQUE (id_voluntario, id_oportunidade),

    CONSTRAINT chk_status_candidatura
        CHECK (status_candidatura IN (
            'PENDENTE',
            'ACEITA',
            'RECUSADA'
        ))
);


CREATE TABLE documento_necessario (
    id_documento_necessario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_oportunidade BIGINT NOT NULL,
    nome_documento VARCHAR(150) NOT NULL,

    CONSTRAINT fk_documento_necessario_oportunidade
        FOREIGN KEY (id_oportunidade)
        REFERENCES oportunidade(id_oportunidade)
        ON DELETE CASCADE,

    CONSTRAINT uq_documento_necessario
        UNIQUE (id_oportunidade, nome_documento)
);


CREATE TABLE documento_enviado (
    id_documento_enviado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidatura BIGINT NOT NULL,
    id_documento_necessario BIGINT NOT NULL,
    nome_original VARCHAR(255) NOT NULL,
    chave_arquivo TEXT NOT NULL,
    data_envio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_documento_enviado_candidatura
        FOREIGN KEY (id_candidatura)
        REFERENCES candidatura(id_candidatura)
        ON DELETE CASCADE,

    CONSTRAINT fk_documento_enviado_necessario
        FOREIGN KEY (id_documento_necessario)
        REFERENCES documento_necessario(id_documento_necessario)
        ON DELETE RESTRICT,

    CONSTRAINT uq_documento_enviado
        UNIQUE (id_candidatura, id_documento_necessario)
);



CREATE TABLE atividade_realizada (
    id_atividade BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidatura BIGINT NOT NULL UNIQUE,
    data_atividade_realizada DATE NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    descricao TEXT,
    horas_realizadas INTEGER,

    CONSTRAINT fk_atividade_candidatura
        FOREIGN KEY (id_candidatura)
        REFERENCES candidatura(id_candidatura)
        ON DELETE RESTRICT

   
);

CREATE TABLE certificado (
    id_certificado BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atividade BIGINT NOT NULL UNIQUE,
    nome_original VARCHAR(255) NOT NULL,
    chave_arquivo TEXT NOT NULL,
    data_emissao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_certificado_atividade
        FOREIGN KEY (id_atividade)
        REFERENCES atividade_realizada(id_atividade)
        ON DELETE RESTRICT
);


CREATE TABLE avaliacao (
    id_avaliacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_atividade BIGINT NOT NULL UNIQUE,
    nota INTEGER NOT NULL,
    comentario TEXT,

    CONSTRAINT fk_avaliacao_atividade
        FOREIGN KEY (id_atividade)
        REFERENCES atividade_realizada(id_atividade)
        ON DELETE CASCADE,

    CONSTRAINT chk_nota
        CHECK (nota BETWEEN 1 AND 5)
);